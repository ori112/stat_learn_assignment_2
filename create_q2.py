    "    X_surv = sm.add_constant(X_lasso_df[survivor_names])\n"
    "    relaxed_lasso_model = sm.OLS(y_ser_q2, X_surv).fit()\n"
    "    print('\\nRelaxed LASSO — OLS on survivors:')\n"
    "    print(relaxed_lasso_model.summary())\n"
    "\n"
