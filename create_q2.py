    "## Q2.5 — Relaxed LASSO (10-fold CV)\n\n"
    "Same algorithm as Q1.5:\n"
    "1. Standardise all predictors.\n"
    "2. LASSO with 10-fold CV to choose $\\lambda$.\n"
